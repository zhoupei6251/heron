-- 原型项目与不可变版本。仅由授权迁移执行，时间统一 UTC。
CREATE TABLE heron_proto_project (
    project_id bigint NOT NULL,
    owner_id bigint NOT NULL,
    name varchar(100) NOT NULL,
    requirement text NOT NULL,
    canvas varchar(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    theme_key varchar(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    revision bigint NOT NULL DEFAULT 1,
    next_version int NOT NULL DEFAULT 1,
    current_version_id bigint NULL,
    active_task_id bigint NULL,
    archived char(1) NOT NULL DEFAULT '0',
    create_dept bigint NULL,
    create_by bigint NULL,
    create_time datetime(3) NOT NULL,
    update_by bigint NULL,
    update_time datetime(3) NOT NULL,
    PRIMARY KEY (project_id),
    KEY ix_proto_project_owner (owner_id, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE heron_proto_version (
    version_id bigint NOT NULL,
    project_id bigint NOT NULL,
    owner_id bigint NOT NULL,
    version_no int NOT NULL,
    task_id bigint NOT NULL,
    input_snapshot json NOT NULL,
    artifact_manifest json NULL,
    engine_commit varchar(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    template_manifest json NULL,
    audit_result json NULL,
    review_status varchar(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
    review_by bigint NULL,
    review_at datetime(3) NULL,
    review_reason varchar(1000) NULL,
    review_preview_sha char(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    review_rp_sha char(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    native_verifications json NULL,
    delivery_request_key varchar(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    delivery_by bigint NULL,
    delivery_at datetime(3) NULL,
    delivery_preview_sha char(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    delivery_rp_sha char(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    delivery_native_verified tinyint NULL,
    delivery_verification_id char(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    create_dept bigint NULL,
    create_by bigint NULL,
    create_time datetime(3) NOT NULL,
    update_by bigint NULL,
    update_time datetime(3) NOT NULL,
    PRIMARY KEY (version_id),
    UNIQUE KEY uk_proto_version_no (project_id, version_no),
    UNIQUE KEY uk_proto_version_task (task_id),
    KEY ix_proto_version_review (owner_id, review_status, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
